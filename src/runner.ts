function ensureNonIterableResult(
  result: ExecutionResult | AsyncIterable<ExecutionResult>,
) {
  if (isAsyncIterable(result)) {
    throw new GraphQLError("Async operations not supported");
  }

  return result;
}

export function bindExecutor(executor: Executor): BindExecutorRequest {
  return (request) => {
    return (document, operationName) => {
      // Persisted query extensions refer to the original document, not to the
      // documents generated by Mangrove.
      const { extensions, ...rest } = request as ExecutionRequest;
      const otherExtensions = { ...(extensions ?? {}) };
      delete otherExtensions.persistedQuery;
      const resultOrPromise = executor({
        ...rest,
        document,
        extensions: otherExtensions,
        operationName,
      });

      if (isPromise(resultOrPromise)) {
        return resultOrPromise.then(ensureNonIterableResult);
      }

      return ensureNonIterableResult(resultOrPromise);
    };
  };
}

export function bindExecute(
  executeFn: typeof defaultExecute,
): BindExecutionArgs {
  return (args) => {
    return (document, operationName) => {
      return executeFn({ ...args, document, operationName });
    };
  };
}

function getArgsFromExecutionArgs(executionArgs: ExecutionArgs): RunQueryArgs {
  return {
    context: executionArgs.contextValue,
    document: executionArgs.document,
    operationName: executionArgs.operationName ?? undefined,
    variables: executionArgs.variableValues,
  };
}

function getArgsFromExecutorRequest(request: ExecutionRequest): RunQueryArgs {
  return {
    context: request.context,
    document: request.document,
    operationName: request.operationName,
    variables: request.variables,
  };
}

export interface LayeredCacheExecuteParameter {
  linkSelections: Record<string, SelectionSetNode>;
  originalOperationName?: string;
  partialQuery?: DocumentNode;
  resolvers: CacheResolverMap;
  runQuery: RunQuery;
  /** Entities available in the cached result, by coordinates. */
  snapshots?: EntitySnapshots;
  /** Variable definitions of the original operation. */
  variableDefinitions?: readonly VariableDefinitionNode[];
}

/**
 * Executes the partial query, then keeps executing link queries for every
 * linked entity that the cache has no data for at that position, until there
 * are none left.
 */
export async function layeredCacheExecute({
  runQuery,
  resolvers,
  linkSelections,
  snapshots = new EntitySnapshots(),
  originalOperationName,
  partialQuery,
  variableDefinitions = [],
}: LayeredCacheExecuteParameter): Promise<{
  linkQueries: DocumentNode[];
  result: ExecutionResult[];
}> {
  if (!partialQuery) {
    return { linkQueries: [], result: [] };
  }

  let nextResult = await runQuery(partialQuery, originalOperationName);

  const nextResults = [nextResult];
  const linkQueries: DocumentNode[] = [];

  if (!nextResult.data || nextResult.errors?.length) {
    return { linkQueries, result: nextResults };
  }

  const collectLinks = makeLinkCollector(snapshots);

  for (let round = 0; ; round++) {
    const links = collectLinks(nextResult.data);

    if (links.length === 0) {
      break;
    }

    if (round >= MAX_LINK_ROUNDS) {
      throw new CacheMergeError(
        `Exceeded ${MAX_LINK_ROUNDS} rounds of link queries`,
      );
    }

    const linkQueryResult = buildLinkQuery({
      linkSelections,
      links,
      originalOperationName,
      resolvers,
      variableDefinitions,
    });

    if (!linkQueryResult) {
      break;
    }

    const { document: linkQuery, operationName } = linkQueryResult;

    nextResult = await runQuery(linkQuery, operationName);

    linkQueries.push(linkQuery);
    nextResults.push(nextResult);

    if (!nextResult.data || nextResult.errors?.length) {
      break;
    }
  }

  return { linkQueries, result: nextResults };
}

function stripMarkers(result: ExecutionResult): ExecutionResult {
  if (!result.data) {
    return result;
  }
  return { ...result, data: cleanupData(result.data) };
}

export function makeQueryRunner({
  buildResponseCacheKey = defaultBuildResponseCacheKey,
  cacheResolvers,
  enabled,
  session,
  getDocumentString = defaultGetDocumentString,
  getPartialExecutionOpts,
  logger = console,
  processResult,
  formatResult = ({ result }) => result,
}: MakeQueryRunnerParameter) {
  return async function runQuery(runner: RunQuery, args: RunQueryArgs) {
    const operationName = args.operationName ?? undefined;
    const operation = getOperation(args.document, operationName);

    if (
      (enabled && !enabled(args.context)) ||
      !operation ||
      operation.operation !== OperationTypeNode.QUERY ||
      isIntrospectionDocument(args.document)
    ) {
      // Documents may have been decorated with Mangrove's marker fields by
      // the parser; make sure they don't reach the client.
      return stripMarkers(await runner(args.document, operationName));
    }

    const sessionId = session(args.context);

    const cacheKey = await buildResponseCacheKey({
      context: args.context,
      documentString: getDocumentString(args),
      operationName,
      sessionId,
      variableValues: args.variables,
    });

    let partialExecutionOpts: PartialExecutionOpts;

    try {
      partialExecutionOpts = await getPartialExecutionOpts({
        cacheKey,
        operationName,
        query: args.document,
        resolvers: cacheResolvers,
      });
    } catch (err) {
      logger.error(
        "Unable to read from cache, falling back to uncached execution",
      );
      logger.error(err);
      // Without the strategy's read state the result can't be stored safely.
      return stripMarkers(await runner(args.document, operationName));
    }

    const { result: cachedResult, cacheState } = partialExecutionOpts;
    let { query, linkSelections } = partialExecutionOpts;

    const mergeContext = createMergeContext(
      cachedResult?.data,
      partialExecutionOpts.prunedCoordinates,
    );

    let linkQueries: DocumentNode[] = [];
    let processed: Awaited<ReturnType<typeof processResult>>;
    let usedCachedResult = cachedResult;

    try {
      const layered = await layeredCacheExecute({
        linkSelections,
        originalOperationName: operationName ?? operation.name?.value,
        partialQuery: query,
        resolvers: cacheResolvers,
        runQuery: runner,
        snapshots: mergeContext.snapshots,
        variableDefinitions: operation.variableDefinitions ?? [],
      });

      linkQueries = layered.linkQueries;

      if (
        cachedResult !== undefined &&
        layered.result.some((result) => result.errors?.length)
      ) {
        // Error paths refer to the generated documents and the partial data
        // can't be trusted; get the real thing instead.
        throw new CacheMergeError("Partial execution returned errors");
      }

      processed = await processResult({
        cacheKey,
        cacheState,
        cachedResult,
        mergeContext,
        nextResults: layered.result,
        originalDocument: args.document,
      });
    } catch (err) {
      if (cachedResult === undefined) {
        throw err;
      }

      logger.warn(
        `Partial execution could not be completed, executing the full operation instead: ${
          err instanceof Error ? err.message : String(err)
        }`,
      );

      const fullResult = await runner(args.document, operationName);

      query = args.document;
      linkSelections = {};
      linkQueries = [];
      usedCachedResult = undefined;

      processed = await processResult({
        cacheKey,
        cacheState,
        nextResults: [fullResult],
        originalDocument: args.document,
      });
    }

    const { result, collectedEntities } = processed;

    const contextValue = (args.context ?? {}) as object;

    if ("collectResourceIdentifier" in contextValue) {
      // Lets live query implementations know which entities a result depends on.
      for (const { entity } of collectedEntities) {
        (
          contextValue.collectResourceIdentifier as (
            entity: EntityRecord,
          ) => void
        )(entity);
      }
    }

    return formatResult({
      cacheKey,
      cachedResult: usedCachedResult as CachedExecutionResult | undefined,
      collectedEntities,
      linkQueries,
      query,
      result,
    });
  };
}

export function makeExecuteWrapper(parameter: MakeQueryRunnerParameter) {
  const runQuery = makeQueryRunner(parameter);
  function wrapExecute(
    executeFn: typeof defaultExecute,
  ): typeof defaultExecute {
    const bindExecuteQuery = bindExecute(executeFn);

    return async function execute(args) {
      const executeQuery = bindExecuteQuery(args);
      return runQuery(executeQuery, getArgsFromExecutionArgs(args));
    };
  }

  return wrapExecute;
}

export function makeExecutorWrapper(parameter: MakeQueryRunnerParameter) {
  const runQuery = makeQueryRunner(parameter);
  function wrapExecutor(executor: Executor): Executor {
    const bindExecuteQuery = bindExecutor(executor);

    return async function executor<TReturn>(request: ExecutionRequest) {
      const executeQuery = bindExecuteQuery(request);
      return runQuery(
        executeQuery,
        getArgsFromExecutorRequest(request),
      ) as TReturn;
    };
  }

  return wrapExecutor;
}
